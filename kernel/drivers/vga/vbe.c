#include "vbe.h"

/* Port-I/O wrappers, inlined here to keep the driver dependency-free. */

static inline void outw(uint16_t port, uint16_t val) {
    __asm__ volatile ("outw %0, %1" : : "a"(val), "Nd"(port));
}

static inline uint16_t inw(uint16_t port) {
    uint16_t ret;
    __asm__ volatile ("inw %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

static inline uint8_t inb(uint16_t port) {
    uint8_t ret;
    __asm__ volatile ("inb %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

uint16_t vbe_read(uint16_t index) {
    outw(VBE_DISPI_IOPORT_INDEX, index);
    return inw(VBE_DISPI_IOPORT_DATA);
}

void vbe_write(uint16_t index, uint16_t value) {
    outw(VBE_DISPI_IOPORT_INDEX, index);
    outw(VBE_DISPI_IOPORT_DATA, value);
}

int vbe_present(void) {
    return (vbe_read(VBE_DISPI_INDEX_ID) & 0xFFF0u) == 0xB0C0u;
}

int vga_vblank_active(void) {
    return (inb(VGA_IN_STATUS_1) & VGA_IN_STATUS_VR) != 0;
}
